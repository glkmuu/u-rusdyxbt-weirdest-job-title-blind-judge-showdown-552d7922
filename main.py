#!/usr/bin/env python3
"""Write the weird job title entry to /output/entry.txt and entry.txt.

Standard library only. The entry is a fixed string, never random and
never generated by an LLM call.
"""

import os

ENTRY = "Senior Penguin Relocation Specialist"

MAX_LENGTH = 60


def validate_entry(entry):
    """Check the gate: UTF-8 text, 1-60 characters, not only whitespace."""
    if not isinstance(entry, str):
        return False
    if not 1 <= len(entry) <= MAX_LENGTH:
        return False
    if entry.strip() == "":
        return False
    if entry != entry.strip():
        return False
    try:
        entry.encode("utf-8")
    except UnicodeEncodeError:
        return False
    return True


def write_entry(path):
    """Write ENTRY to path with no trailing newline, then verify it."""
    with open(path, "w", encoding="utf-8", newline="") as f:
        f.write(ENTRY)
    with open(path, "r", encoding="utf-8", newline="") as f:
        if f.read() != ENTRY:
            raise ValueError("written entry does not match ENTRY: %s" % path)


def main():
    if not validate_entry(ENTRY):
        raise ValueError("entry failed validation")
    os.makedirs("/output", exist_ok=True)
    write_entry("/output/entry.txt")
    here = os.path.dirname(os.path.abspath(__file__))
    write_entry(os.path.join(here, "entry.txt"))


if __name__ == "__main__":
    main()
